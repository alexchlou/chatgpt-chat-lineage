#!/usr/bin/env python3
"""Build a fictional, offline research network. Never opens a browser or sends mail."""
import argparse
import hashlib
import json
from pathlib import Path
import research_journal as journal
import knowledge_graph as graph
import obsidian_export

ROWS = [
    ('heat-equity', 'Help with research', 'Urban Heat | Shade access equity research design', ['heat-adaptation','urban-equity']),
    ('sensor-privacy', 'More analysis', 'Sensor Privacy | Compare aggregation and retention policies', ['sensor-data','privacy']),
    ('transit-access', 'Transit Access | Accessible stop audit protocol', 'Transit Access | Accessible stop audit protocol', ['urban-equity','accessibility']),
    ('cool-corridors', 'Street trees', 'Cool Corridors | Compare shade mapping methods', ['heat-adaptation','public-space']),
    ('procurement', 'Public Procurement | Evaluate municipal data clauses', 'Public Procurement | Evaluate municipal data clauses', ['public-procurement','data-governance']),
    ('citizen-sensors', 'Workshop notes', 'Citizen Sensors | Design a community monitoring protocol', ['sensor-data','participation']),
    ('data-stewardship', 'Data Stewardship | Review shared dataset responsibilities', 'Data Stewardship | Review shared dataset responsibilities', ['data-governance']),
    ('birdsong', 'Bioacoustics | Compare birdsong annotation methods', 'Bioacoustics | Compare birdsong annotation methods', ['bioacoustics'])
]


def url(index): return 'https://chatgpt.com/c/synthetic-' + ROWS[index][0]


def event(index, keep=False):
    _, old, title, tags = ROWS[index]
    kept = keep or old == title
    return {'conversation_url':url(index),'stage':'RESULT','status':'ALREADY CORRECT' if kept else 'RENAMED',
            'decision':'keep' if kept else 'rename','proposed_title':title,'displayed_title':title,
            'rationale':'Fictional metadata for a public software demo; not a browser observation.',
            'reason_codes':['EXISTING_TITLE_ADEQUATE' if kept else 'MISSING_TASK'],
            'topic_labels':tags,'task_type':'research','annotation_basis':'visible_context',
            'context_level':'outline','observed_at':'2025-01-01T12:00:00+00:00',
            'save_attempted':not kept,'verification':{key:True for key in journal.CHECKS}}


def build(output):
    output = Path(output).resolve()
    if output.exists() and (not output.is_dir() or any(output.iterdir())):
        raise ValueError('Choose a new or empty output directory; private datasets are never overwritten')
    output.mkdir(parents=True, exist_ok=True)
    previous_clock = journal.utc_now
    journal.utc_now = lambda: '2025-01-01T12:00:00+00:00'
    try:
        journal.init(output, allow_synthetic=True)
        folder = output/'knowledge_graph';folder.mkdir()
        (folder/'config.json').write_text('{"enabled":true}\n')
        run = {'run_id':'synthetic-demo-day-1','event_date':'2025-01-01','timezone':'UTC','mode':'apply',
               'source_type':'synthetic','source_ref':'Fictional public demo generated by scripts/build_demo.py',
               'skill_version':json.loads((Path(__file__).resolve().parents[1]/'manifest.json').read_text())['version'],
               'scope_kind':'exact_urls','selection_rule':'Eight fictional examples; no real sidebar selection',
               'requested_count':len(ROWS),'exclude_pinned':True,
               'triggered_at':'2025-01-01T12:00:00+00:00','limitations':['Synthetic demonstration only; no live UI or real research findings.'],
               'targets':[{'conversation_url':url(i),'original_title':r[1]} for i,r in enumerate(ROWS)]}
        events=[event(i) for i in range(len(ROWS))]
        blocked=event(6);blocked.update(status='BLOCKED',decision='undetermined',proposed_title=None,displayed_title=None,
            topic_labels=[],reason_codes=['BODY_NOT_READY'],save_attempted=False,
            verification={k:None for k in journal.CHECKS},rationale='Fictional loading failure; no body read and no save.')
        events[6]=blocked
        bundle={'run':run,'events':events,'final_state':'PARTIAL'}
        journal.ingest(output,bundle)
        baseline=journal.export(output)
        before=journal.stats(output)
        replay=journal.ingest(output,bundle)
        assert replay['events_inserted']==0 and journal.stats(output)==before
        assert journal.export(output)['knowledge_graph']['update_id']==baseline['knowledge_graph']['update_id']
        original=journal.resume_run(output,run['run_id'])['targets'][6]['latest_event_id']
        journal.reopen_run(output,run['run_id'])
        correction=event(6);correction.update(stage='CORRECTION',supersedes_event_id=original,
            observed_at='2025-01-01T12:10:00+00:00',rationale='Fictional recovered page; the existing title remains adequate; no save.')
        journal.record_event(output,run['run_id'],correction)
        journal.record_event(output,run['run_id'],correction)
        journal.finish_run(output,run['run_id'],'COMPLETE')
        g,_=graph.derive(graph.snapshot(output));engine=graph.relation_engine()
        runs={n['label']:n['properties'] for n in g['nodes'] if n['type']=='Run'}
        support={n['properties']['conversation_url']:engine.support_record(n,runs) for n in g['nodes'] if n['type']=='Observation'}
        doc={'path':'scripts/build_demo.py','sha256':hashlib.sha256(Path(__file__).read_bytes()).hexdigest()}
        assertions=[]
        relations=[
            (0,2,'E1','METADATA_SUBJECT_OVERLAP','Access equity across shade and transit','Both fictional naming summaries explicitly concern access equity.','Compare populations, access metrics, and the full study designs.'),
            (1,4,'E1','EXPLICIT_METADATA_OVERLAP','Data policy and public purchasing','Both fictional summaries address data-policy responsibilities.','Check the actual policy clauses and procurement documents.'),
            (3,5,'H','CANDIDATE_METHOD_TRANSFER','Could community sensors improve shade maps?','Fictional metadata suggests compatible environmental measurement tasks.','Test calibration, spatial coverage, bias, and a counterexample where low-cost sensors fail.'),
            (1,6,'H','CANDIDATE_GOVERNANCE_COMPARISON','Compare privacy and stewardship responsibilities','The fictional topics suggest a governance comparison, not an established mechanism.','Read the relevant materials and identify incompatible definitions or responsibilities.'),
            (2,4,'H','CANDIDATE_POLICY_APPLICATION','Can procurement clauses support accessible transit audits?','A possible link between a fictional accessibility task and a procurement task.','Find actual procurement requirements and assess whether they address accessibility evidence.')]
        for number,(a,b,tier,kind,label,evidence,needed) in enumerate(relations,1):
            assertions.append({'id':'synthetic-relation-'+str(number),'source_url':url(a),'target_url':url(b),
                'tier':tier,'relation':kind,'label':label,'evidence':evidence,'validation_needed':needed,
                'support':[support[url(a)],support[url(b)]],'source_documents':[doc],
                'validation_status':'METADATA_COMPATIBILITY_ONLY' if tier=='E1' else 'PENDING_VALIDATION'})
        domains=[{'id':'urban-systems','label':'Urban systems','question':'How can urban services improve equitable access?','basis':'Fictional analyst coding of approved naming metadata.'},
                 {'id':'data-governance','label':'Data governance','question':'How should measurement data be governed?','basis':'Fictional analyst coding of approved naming metadata.'}]
        annotations=[{'url':url(i),'code':'C'+str(i+1),'short_label':r[2].split(' | ')[0],
                      'domains':(['urban-systems'] if i in (0,2,3) else ['data-governance'] if i in (1,4,5,6) else []),
                      'support':[support[url(i)]],'source_documents':[doc]} for i,r in enumerate(ROWS)]
        registry={'schema_version':'1.0.0','basis':'Fictional public demonstration, not research evidence.',
                  'assertions':assertions,'domains':domains,'conversation_annotations':annotations}
        (folder/'relationship_registry.json').write_text(json.dumps(registry,indent=2)+'\n')
        final=journal.export(output)
        updates=(folder/'updates.jsonl').read_bytes()
        again=journal.export(output)
        assert final==again and updates==(folder/'updates.jsonl').read_bytes()
        vault=output/'obsidian-demo'
        first_sync=obsidian_export.sync(output,vault,True)
        second_sync=obsidian_export.sync(output,vault)
        assert second_sync['created']==second_sync['updated']==0
        assert first_sync['notes']==second_sync['unchanged']
        graph_data=json.loads((folder/'graph.json').read_text())
        assert {n['properties']['source_type'] for n in graph_data['nodes'] if n['type']=='Observation'}=={'synthetic'}
        summary={'source_type':'synthetic','real_chats_read':0,'real_saves':0,'emails_sent':0,
                 'conversations':len(ROWS),'retained_blocked_events':1,'corrections':1,
                 'relation_counts':final['knowledge_graph']['research_relation_counts'],
                 'update_id':final['knowledge_graph']['update_id'],'obsidian_notes':second_sync['notes'],
                 'idempotency':{'event_retry':'PASS','graph_export':'PASS','obsidian_sync':'PASS'}}
        (output/'demo-summary.json').write_text(json.dumps(summary,indent=2)+'\n')
        return summary
    finally:
        journal.utc_now=previous_clock


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--output',required=True)
    print(json.dumps(build(parser.parse_args().output),indent=2))
